DELIMITER //
CREATE PROCEDURE ADDBONUS(IN EMPID INT,INOUT BONUS DECIMAL(10,2))
BEGIN
UPDATE EMPLOYEES SET SALARY=SALARY+BONUS WHERE EMP_ID=EMPID;

SELECT SALARY INTO BONUS FROM EMPLOYEES WHERE EMP_ID=EMPID;
END //
DELIMITER ;
SET @B=5000;
CALL ADDBONUS(101,@B);
SELECT @B;  

DELIMITER //
CREATE PROCEDURE REMOVEBONUS(IN EMPID INT,INOUT BONUS DECIMAL(10,2))
BEGIN
UPDATE EMPLOYEES SET SALARY=SALARY-BONUS WHERE EMP_ID=EMPID;

SELECT SALARY INTO BONUS FROM EMPLOYEES WHERE EMP_ID=EMPID;
END //
DELIMITER ;
SET @A=5000;
CALL REMOVEBONUS(101,@A);
SELECT @A;



